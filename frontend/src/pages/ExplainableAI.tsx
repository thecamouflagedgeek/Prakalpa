function riskColor(risk: string): { fg: string; bg: string; bar: string } {
  const r = risk.trim().toLowerCase();
  if (r === "critical") return { fg: "#7A1F1F", bg: "#FBEBEA", bar: "#C94B4B" };
  if (r === "high" || r === "spike")
    return { fg: "#A13D1F", bg: "#FCEEE4", bar: "#E07A3E" };
  if (r === "medium")
    return { fg: "#8A6D00", bg: "#FBF3D6", bar: "#D9A80B" };
  if (r === "low" || r === "drop")
    return { fg: TEAL_DARK, bg: TEAL_TINT, bar: TEAL };
  return { fg: MUTED, bg: BG_SECTION, bar: MUTED };
}

