/** Flat objects of primitives render as a label/value grid; arrays of
 * records render as wrapping cards (not one wide row per record — that's
 * what used to blow out the page width); anything else nested renders as
 * an indented list so it's still readable without knowing the exact schema
 * ahead of time. `level` only affects styling (top-level sections read as
 * headings), never the data itself. */
function Register({ data, level = 0 }: { data: JsonValue; level?: number }) {
  if (data === null || data === undefined) {
    return <div style={styles.emptyState}>No data returned.</div>;
  }

  if (typeof data !== "object") {
    return <div style={styles.registerValue}>{String(data)}</div>;
  }

  if (Array.isArray(data)) {
    if (data.length === 0) {
      return <div style={styles.emptyState}>No data returned.</div>;
    }

    const allRecords = data.every(
      (v) => v !== null && typeof v === "object" && !Array.isArray(v),
    );

    if (allRecords) {
      return (
        <div style={styles.evidenceCardGrid}>
          {data.map((v, i) => (
            <div key={i} style={styles.evidenceCard}>
              <div style={styles.evidenceCardIndex}>Item {i + 1}</div>
              <Register data={v} level={level + 1} />
            </div>
          ))}
        </div>
      );
    }

    // Array of primitives (or mixed) — a tag row reads better than an
    // index-keyed list.
    return (
      <div style={styles.tagRow}>
        {data.map((v, i) => (
          <span key={i} style={styles.evidenceTag}>
            {v === null ? "—" : String(v)}
          </span>
        ))}
      </div>
    );
  }

  const entries = Object.entries(data as JsonRecord);

  if (entries.length === 0) {
    return <div style={styles.emptyState}>No data returned.</div>;
  }

  const isFlat = entries.every(([, v]) => v === null || typeof v !== "object");

  if (isFlat) {
    return (
      <div style={styles.registerGrid}>
        {entries.map(([k, v]) => (
          <div key={k} style={styles.registerCell}>
            <div style={styles.registerLabel}>{formatLabel(k)}</div>
            <div style={styles.registerValue}>
              {v === null ? "—" : String(v)}
            </div>
          </div>
        ))}
      </div>
    );
  }

  return (
    <div style={styles.registerNested}>
      {entries.map(([k, v]) => (
        <div key={k} style={level === 0 ? styles.nestedSection : styles.nestedRow}>
          <div style={level === 0 ? styles.subHeading : styles.registerLabel}>
            {formatLabel(k)}
          </div>
          {v !== null && typeof v === "object" ? (
            <div style={level === 0 ? { marginTop: 8 } : styles.nestedIndent}>
              <Register data={v} level={level + 1} />
            </div>
          ) : (
            <div style={styles.registerValue}>
              {v === null ? "—" : String(v)}
            </div>
          )}
        </div>
      ))}
    </div>
  );
}

function formatLabel(key: string): string {
  return key.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

// ---------- Safe accessors (defensive against schema drift) ----------

const asRec = (v: JsonValue | undefined | null): JsonRecord =>
  v && typeof v === "object" && !Array.isArray(v) ? (v as JsonRecord) : {};
const asArr = (v: JsonValue | undefined | null): JsonValue[] =>
  Array.isArray(v) ? v : [];
const asRecArr = (v: JsonValue | undefined | null): JsonRecord[] =>
  asArr(v).filter(
    (x) => x && typeof x === "object" && !Array.isArray(x),
  ) as JsonRecord[];
const asStr = (v: JsonValue | undefined | null): string =>
  v === null || v === undefined ? "" : String(v);
const asNum = (v: JsonValue | undefined | null): number =>
  typeof v === "number" ? v : Number(v) || 0;

