/** Renders "## Heading" markdown-lite blocks as distinct sections instead
 * of one giant run-on paragraph with literal hash characters in it. */
function MarkdownLite({ text }: { text: string }) {
  if (!text) return null;
  const parts = text.split(/\n*##\s+/).filter(Boolean);
  // If there's no "## " structure at all, just render as a paragraph.
  if (parts.length <= 1) {
    return <p style={styles.summaryText}>{text}</p>;
  }
  return (
    <div style={{ display: "flex", flexDirection: "column", gap: 12 }}>
      {parts.map((part, i) => {
        const firstBreak = part.indexOf(" ");
        // First word(s) up to a period-free short run acts as the heading;
        // fall back gracefully if the model didn't format cleanly.
        const match = part.match(/^([A-Za-z &/]{3,40}?)\s+(.*)$/s);
        const heading = match ? match[1].trim() : `Section ${i + 1}`;
        const body = match ? match[2].trim() : part.trim();
        return (
          <div key={i}>
            <div style={styles.mdHeading}>{heading}</div>
            <p style={styles.summaryText}>{body || part}</p>
          </div>
        );
      })}
    </div>
  );
}

