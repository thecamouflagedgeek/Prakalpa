function AnomaliesBlock({ data }: { data: JsonValue }) {
  const a = asRec(data);
  const knownShape = "anomalies" in a || "analysis_window" in a;
  if (!knownShape) return <Register data={data} />;

  const list = asRecArr(a.anomalies);
  const exec = asRec(a.executive_summary);

  return (
    <div>
      {Object.keys(exec).length > 0 && (
        <div style={styles.statGridSmall}>
          {exec.overall_threat && (
            <MiniStat label="Threat" value={asStr(exec.overall_threat)} accent />
          )}
          {exec.critical_alerts !== undefined && (
            <MiniStat label="Critical" value={asStr(exec.critical_alerts)} />
          )}
          {exec.high_alerts !== undefined && (
            <MiniStat label="High" value={asStr(exec.high_alerts)} />
          )}
          {exec.total_anomalies !== undefined && (
            <MiniStat label="Total" value={asStr(exec.total_anomalies)} />
          )}
        </div>
      )}
      {exec.summary && (
        <p style={{ ...styles.summaryText, marginTop: 10 }}>{asStr(exec.summary)}</p>
      )}

      {list.length > 0 ? (
        <div style={{ marginTop: 12, display: "flex", flexDirection: "column", gap: 6 }}>
          {list.map((an, i) => (
            <div key={i} style={styles.miniCard}>
              <div style={styles.miniCardHead}>
                <div style={styles.miniCardTitle}>{asStr(an.crime)}</div>
                <RiskBadge risk={asStr(an.severity) || asStr(an.type)} />
              </div>
              <div style={styles.miniCardFoot}>
                {asStr(an.type)} · {asStr(an.change_percent)}% change
              </div>
              {an.reason && <div style={styles.miniCardFoot}>{asStr(an.reason)}</div>}
            </div>
          ))}
        </div>
      ) : (
        Object.keys(exec).length === 0 && <Empty />
      )}

      {a.explainability && (
        <div style={{ marginTop: 10, fontSize: 11.5, color: MUTED, fontStyle: "italic" }}>
          {asStr(a.explainability)}
        </div>
      )}
    </div>
  );
}

